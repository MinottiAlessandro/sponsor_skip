// Resolved current language + helpers. Shared globally (classic script).
const I18N = {
  lang: "en",
  resolve(setting) {
    if (setting && setting !== "auto" && MESSAGES[setting]) return setting;
    let ui = "en";
    try { ui = chrome.i18n?.getUILanguage?.() || navigator.language || "en"; }
    catch { ui = (typeof navigator !== "undefined" && navigator.language) || "en"; }
    const two = String(ui).slice(0, 2).toLowerCase();
    return MESSAGES[two] ? two : "en";
  },
  setLang(setting) { this.lang = this.resolve(setting); return this.lang; },
};

function t(key, params) {
  const table = MESSAGES[I18N.lang] || MESSAGES.en;
  let s = table[key] ?? MESSAGES.en[key] ?? key;
  if (params) for (const k in params) s = s.replaceAll(`{${k}}`, params[k]);
  return s;
}

// Plural picker: en/it/es/fr/de all split on n === 1 for these short UI strings.
function tn(n, oneKey, manyKey, params) {
  return t(n === 1 ? oneKey : manyKey, { ...(params || {}), n });
}
